def col_letter(col_idx: int) -> str:
    """Converts 0-based column index to Excel column name (0 -> A, 27 -> AB)."""
    result = ""
    while col_idx >= 0:
        result = chr(col_idx % 26 + 65) + result
        col_idx = col_idx // 26 - 1
    return result


def sanitize_xml(text: Any) -> str:
    """Escapes string for safe XML text inclusion."""
    if text is None:
        return ""
    s = str(text)
    # Remove control characters invalid in XML
    s = re.sub(r"[\x00-\x08\x0B\x0C\x0E-\x1F]", "", s)
    return html.escape(s)


def sanitize_sheet_name(name: str) -> str:
    """Sanitizes sheet title for Excel/ODS tab name constraints."""
    cleaned = re.sub(r"[\\/*?:\[\]]", "_", name)
    return cleaned[:31] if cleaned else "Sheet"


def pd_isna(val: Any) -> bool:
    """Checks if a scalar value is None or NaN without pandas dependency."""
    if val is None:
        return True
    try:
        return bool(np.isnan(val))
    except Exception:
        return False


class RichRun:
    """Represents a formatted run of text within a rich paragraph."""

    def __init__(
        self,
        text: str,
        bold: bool = False,
        italic: bool = False,
        underline: bool = False,
        font_family: str = "",
        font_size_pt: float = 0.0,
    ) -> None:
        self.text = text
        self.bold = bold
        self.italic = italic
        self.underline = underline
        self.font_family = font_family
        self.font_size_pt = font_size_pt


class RichParagraph:
    """Represents a paragraph or bullet item with styled runs."""

    def __init__(
        self,
        is_bullet: bool = False,
        indent: int = 0,
        runs: Optional[List[RichRun]] = None,
    ) -> None:
        self.is_bullet = is_bullet
        self.indent = indent
        self.runs: List[RichRun] = runs if runs is not None else []


class NotesHTMLParser(HTMLParser):
    """Parses HTML generated by RichTextEditor/QTextEdit into RichParagraphs with styled runs."""

    def __init__(self) -> None:
        super().__init__()
        self.paragraphs: List[RichParagraph] = []
        self.current_para: Optional[RichParagraph] = None
        self.in_list_depth: int = 0
        self.tag_stack: List[Dict[str, Any]] = []

    def _ensure_para(self, is_bullet: bool = False, indent: int = 0) -> RichParagraph:
        if self.current_para is None:
            self.current_para = RichParagraph(is_bullet=is_bullet, indent=indent)
        return self.current_para

    def _flush_para(self) -> None:
        if self.current_para is not None:
            if self.current_para.runs:
                self.paragraphs.append(self.current_para)
            self.current_para = None

    def handle_starttag(self, tag: str, attrs: List[Tuple[str, Optional[str]]]) -> None:
        tag_l = tag.lower()
        attr_dict = {k.lower(): (v or "") for k, v in attrs}
        style = attr_dict.get("style", "").lower()

        has_bold = tag_l in ("b", "strong") or (
            "font-weight:700" in style
            or "font-weight: 700" in style
            or "font-weight:bold" in style
            or "font-weight: bold" in style
        )
        has_italic = tag_l in ("i", "em") or (
            "font-style:italic" in style or "font-style: italic" in style
        )
        has_underline = (
            tag_l == "u"
            or "text-decoration: underline" in style
            or "text-decoration:underline" in style
        )

        family = ""
        m_fam = re.search(r"font-family:\s*['\"]?([^;'\"#]+)", style)
        if m_fam:
            f_cand = m_fam.group(1).split(",")[0].strip()
            if "serif" in f_cand.lower() and "sans" not in f_cand.lower():
                family = "Liberation Serif"
            elif "mono" in f_cand.lower() or "courier" in f_cand.lower():
                family = "Liberation Mono"
            elif "sans" in f_cand.lower():
                family = "Liberation Sans"
            else:
                family = f_cand

        size_pt = 0.0
        m_sz = re.search(r"font-size:\s*(\d+(?:\.\d+)?)pt", style)
        if m_sz:
            try:
                size_pt = float(m_sz.group(1))
            except ValueError:
                pass

        block_indent = 0
        m_ind = re.search(r"-qt-block-indent:\s*(\d+)", style)
        if m_ind:
            block_indent = int(m_ind.group(1))
        m_list_ind = re.search(r"-qt-list-indent:\s*(\d+)", style)
        if m_list_ind:
            block_indent = int(m_list_ind.group(1))

        self.tag_stack.append({
            "tag": tag_l,
            "bold": has_bold,
            "italic": has_italic,
            "underline": has_underline,
            "font": family,
            "size": size_pt,
            "indent": block_indent,
        })

        if tag_l in ("ul", "ol"):
            self._flush_para()
            self.in_list_depth += 1
        elif tag_l == "li":
            self._flush_para()
            indent = max(0, self.in_list_depth - 1) + (block_indent or 0)
            self.current_para = RichParagraph(is_bullet=True, indent=indent)
        elif tag_l in ("p", "div", "h1", "h2", "h3", "h4", "h5", "h6"):
            self._flush_para()
            self.current_para = RichParagraph(is_bullet=False, indent=block_indent)
        elif tag_l == "br":
            self._flush_para()

    def handle_endtag(self, tag: str) -> None:
        tag_l = tag.lower()
        if self.tag_stack:
            self.tag_stack.pop()

        if tag_l in ("ul", "ol"):
            self._flush_para()
            self.in_list_depth = max(0, self.in_list_depth - 1)
        elif tag_l in ("li", "p", "div", "h1", "h2", "h3", "h4", "h5", "h6"):
            self._flush_para()

    def handle_data(self, data: str) -> None:
        cleaned = data.strip("\r\n")
        if not cleaned:
            return
        is_bold = any(s["bold"] for s in self.tag_stack)
        is_italic = any(s["italic"] for s in self.tag_stack)
        is_underline = any(s["underline"] for s in self.tag_stack)
        curr_font = next((s["font"] for s in reversed(self.tag_stack) if s["font"]), "")
        curr_size = next((s["size"] for s in reversed(self.tag_stack) if s["size"] > 0), 0.0)
        curr_indent = next((s["indent"] for s in reversed(self.tag_stack) if s["indent"] > 0), 0)

        para = self._ensure_para(is_bullet=(self.in_list_depth > 0), indent=curr_indent)
        para.runs.append(
            RichRun(
                cleaned,
                bold=is_bold,
                italic=is_italic,
                underline=is_underline,
                font_family=curr_font,
                font_size_pt=curr_size,
            )
        )

    def close(self) -> None:
        super().close()
        self._flush_para()


def parse_notes_to_rich_paragraphs(notes_html: str, notes_plain: str) -> List[RichParagraph]:
    """Converts HTML notes (or plain text fallback) into a structured list of RichParagraphs."""
    if notes_html and notes_html.strip():
        try:
            parser = NotesHTMLParser()
            parser.feed(notes_html)
            parser.close()
            if parser.paragraphs:
                return parser.paragraphs
        except Exception:
            pass

    # Fallback to plain text
    paras: List[RichParagraph] = []
    for line in (notes_plain or "").splitlines():
        s_line = line.strip()
        if not s_line:
            continue
        if s_line.startswith("- ") or s_line.startswith("* "):
            paras.append(RichParagraph(is_bullet=True, indent=0, runs=[RichRun(s_line[2:])]))
        else:
            paras.append(RichParagraph(is_bullet=False, indent=0, runs=[RichRun(s_line)]))
    return paras


def _save_canvas_state(canvas: Any) -> Dict[str, Any]:
    """Captures the current state of a graph canvas widget."""
    return {
        "table": getattr(canvas, "current_table", None),
        "result": getattr(canvas, "current_result", None),
        "active_sheet": getattr(canvas, "active_sheet", None),
        "graph_sheet": getattr(canvas, "current_graph_sheet", None),
        "type_idx": canvas.type_combo.currentIndex() if hasattr(canvas, "type_combo") else 0,
        "type_text": canvas.type_combo.currentText() if hasattr(canvas, "type_combo") else "",
        "pal_idx": canvas.palette_combo.currentIndex() if hasattr(canvas, "palette_combo") else 0,
        "pal_text": canvas.palette_combo.currentText() if hasattr(canvas, "palette_combo") else "",
        "whisker_idx": canvas.whisker_dir_combo.currentIndex() if hasattr(canvas, "whisker_dir_combo") else 0,
        "scatter": getattr(canvas, "show_bar_scatter_points", True),
        "colors": dict(getattr(canvas, "custom_series_colors", {})),
        "opacities": dict(getattr(canvas, "custom_series_opacities", {})),
        "styles": dict(getattr(canvas, "series_styles", {})),
        "error_style": getattr(canvas, "error_style", "SEM"),
        "is_gray": getattr(canvas, "is_grayscale_mode", False),
    }


def _restore_canvas_state(canvas: Any, state: Dict[str, Any]) -> None:
    """Restores graph canvas widget to its prior state without triggering external side effects."""
    controls = []
    if hasattr(canvas, "type_combo"):
        controls.append(canvas.type_combo)
    if hasattr(canvas, "palette_combo"):
        controls.append(canvas.palette_combo)
    if hasattr(canvas, "whisker_dir_combo"):
        controls.append(canvas.whisker_dir_combo)
    if hasattr(canvas, "btn_toggle_scatter"):
        controls.append(canvas.btn_toggle_scatter)

    for ctrl in controls:
        ctrl.blockSignals(True)

    try:
        canvas.current_table = state["table"]
        canvas.current_result = state["result"]
        canvas.active_sheet = state["active_sheet"]
        canvas.current_graph_sheet = state["graph_sheet"]
        if hasattr(canvas, "type_combo"):
            idx = canvas.type_combo.findText(state.get("type_text", ""))
            if idx >= 0:
                canvas.type_combo.setCurrentIndex(idx)
            else:
                canvas.type_combo.setCurrentIndex(state["type_idx"])
        if hasattr(canvas, "palette_combo"):
            if state.get("is_gray"):
                canvas.palette_combo.setCurrentIndex(1)
            else:
                idx = canvas.palette_combo.findText(state.get("pal_text", ""))
                if idx >= 0:
                    canvas.palette_combo.setCurrentIndex(idx)
                else:
                    canvas.palette_combo.setCurrentIndex(state["pal_idx"])
        if hasattr(canvas, "whisker_dir_combo"):
            canvas.whisker_dir_combo.setCurrentIndex(state["whisker_idx"])
        if hasattr(canvas, "btn_toggle_scatter"):
            canvas.btn_toggle_scatter.setChecked(state["scatter"])
        canvas.show_bar_scatter_points = state["scatter"]
        canvas.custom_series_colors = dict(state["colors"])
        canvas.custom_series_opacities = dict(state["opacities"])
        canvas.series_styles = dict(state["styles"])
        canvas.error_style = state["error_style"]
        canvas.refresh_plot()
    finally:
        for ctrl in controls:
            ctrl.blockSignals(False)


def render_graph_to_png_bytes(
    graph_sheet: Any,
    document: Any = None,
    graph_canvas: Optional[Any] = None,
    width: int = 1200,
    height: int = 800,
) -> bytes:
    """Renders a GraphSheet or DataSheet to high-DPI PNG bytes offscreen with zero subprocesses and canvas isolation."""
    # Support both calling conventions: (sheet, doc, canvas) and (canvas, sheet)
    if hasattr(graph_sheet, "plot_widget"):
        canvas = graph_sheet
        target_sheet = document
        doc = graph_canvas or (target_sheet.document if hasattr(target_sheet, "document") else PrismDocument())
    else:
        target_sheet = graph_sheet
        doc = document
        canvas = graph_canvas

    created_canvas = False
    saved_state = None
    if canvas is None:
        from src.ui.graph_canvas import GraphCanvasWidget
        canvas = GraphCanvasWidget()
        canvas.resize(width // 2, height // 2)
        created_canvas = True
    else:
        saved_state = _save_canvas_state(canvas)

    try:
        if isinstance(target_sheet, DataSheet):
            src_table = target_sheet.table
            res_sheet = None
            gt = None
        elif isinstance(target_sheet, GraphSheet):
            if target_sheet.is_frozen and getattr(target_sheet, "snapshot_table", None) is not None:
                src_table = target_sheet.snapshot_table
                if getattr(target_sheet, "snapshot_result_data", None):
                    res_sheet = ResultSheet.from_dict(target_sheet.snapshot_result_data)
                elif target_sheet.result_sheet_id:
                    res_sheet = (
                        doc.get_sheet(target_sheet.result_sheet_id)
                        if doc
                        else None
                    )
                else:
                    res_sheet = None
            else:
                src_sheet = doc.get_sheet(target_sheet.source_sheet_id) if doc else None
                src_table = src_sheet.table if isinstance(src_sheet, DataSheet) else None
                res_sheet = (
                    doc.get_sheet(target_sheet.result_sheet_id)
                    if (doc and target_sheet.result_sheet_id)
                    else None
                )
            gt = target_sheet.graph_type
        else:
            src_table = getattr(target_sheet, "table", None)
            res_sheet = None
            gt = None

        canvas.update_data(
            src_table,
            result=res_sheet if isinstance(res_sheet, ResultSheet) else None,
            graph_type=gt,
            sheet=target_sheet,
        )

        # Generous axis margin padding to prevent multi-line categorical/group label truncation
        try:
            bottom_ax = canvas.plot_widget.getAxis("bottom")
            left_ax = canvas.plot_widget.getAxis("left")
            bottom_ax.setHeight(max(60, int(height * 0.12)))
            left_ax.setWidth(max(60, int(width * 0.10)))
        except Exception:
            pass

        img = QImage(width, height, QImage.Format.Format_ARGB32)
        img.fill(QColor(255, 255, 255))
        painter = QPainter(img)
        try:
            canvas.plot_widget.render(painter)
        finally:
            painter.end()

        buffer = QBuffer()
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        img.save(buffer, "PNG")
        data = bytes(buffer.data())
        buffer.close()
        if created_canvas:
            canvas.deleteLater()
        return data
    finally:
        if not created_canvas and saved_state is not None:
            _restore_canvas_state(canvas, saved_state)


class OfficeExporter:
    """Granular document exporter producing standard-compliant .docx, .odt, .xlsx, .ods, and .pdf files."""

    def __init__(self, document: PrismDocument, graph_canvas: Optional[Any] = None) -> None:
        self.document = document
        self.graph_canvas = graph_canvas

    def export(
        self,
        file_path: str,
        fmt: Optional[ExportFormat] = None,
        selected_sheet_ids: Optional[List[str]] = None,
    ) -> str:
        """
        Exports the document or selected items to target file path.
        Infers format from file extension if fmt is not explicitly specified.
        """
        if fmt is None:
            ext = os.path.splitext(file_path)[1].lower().lstrip(".")
            try:
                fmt = ExportFormat(ext)
            except ValueError:
                fmt = ExportFormat.DOCX

        if fmt == ExportFormat.DOCX:
            return self.export_docx(file_path, selected_sheet_ids)
        elif fmt == ExportFormat.ODT:
            return self.export_odt(file_path, selected_sheet_ids)
        elif fmt == ExportFormat.XLSX:
            return self.export_xlsx(file_path, selected_sheet_ids)
        elif fmt == ExportFormat.ODS:
            return self.export_ods(file_path, selected_sheet_ids)
        elif fmt == ExportFormat.PDF:
            return self.export_pdf(file_path, selected_sheet_ids)
        else:
            raise ValueError(f"Unsupported export format: {fmt}")

    def _get_export_items(
        self, selected_sheet_ids: Optional[List[str]]
    ) -> Tuple[List[InfoSheet], List[DataSheet], List[ResultSheet], List[GraphSheet], List[PageLayout]]:
        info_sheets: List[InfoSheet] = []
        data_sheets: List[DataSheet] = []
        result_sheets: List[ResultSheet] = []
        graph_sheets: List[GraphSheet] = []
        layout_sheets: List[PageLayout] = []

        target_ids = set(selected_sheet_ids) if selected_sheet_ids is not None else set(self.document.sheet_order)

        for sid in self.document.sheet_order:
            if sid not in target_ids:
                continue
            sheet = self.document.sheets.get(sid)
            if sheet is None:
                continue
            if sheet.sheet_type == SheetType.INFO and isinstance(sheet, InfoSheet):
                info_sheets.append(sheet)
            elif sheet.sheet_type == SheetType.DATA and isinstance(sheet, DataSheet):
                data_sheets.append(sheet)
            elif sheet.sheet_type == SheetType.RESULTS and isinstance(sheet, ResultSheet):
                result_sheets.append(sheet)
            elif sheet.sheet_type == SheetType.GRAPH and isinstance(sheet, GraphSheet):
                graph_sheets.append(sheet)
            elif sheet.sheet_type == SheetType.LAYOUT and isinstance(sheet, PageLayout):
                layout_sheets.append(sheet)

        return info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets

    # -------------------------------------------------------------------------
    # 1. Word Document (.docx)
    # -------------------------------------------------------------------------
    def export_docx(self, file_path: str, selected_sheet_ids: Optional[List[str]] = None) -> str:
        info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets = self._get_export_items(selected_sheet_ids)

        figure_images: List[Tuple[str, bytes, bool]] = []
        target_graphs = graph_sheets if graph_sheets else (data_sheets if not layout_sheets else [])
        for g in target_graphs:
            try:
                png_bytes = render_graph_to_png_bytes(g, self.document, self.graph_canvas)
                figure_images.append((g.title, png_bytes, False))
            except Exception:
                pass

        for l in layout_sheets:
            try:
                png_bytes = render_layout_to_png_bytes(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                figure_images.append((l.title, png_bytes, True))
            except Exception:
                pass

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            # [Content_Types].xml
            ct_xml = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">',
                '  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
                '  <Default Extension="xml" ContentType="application/xml"/>',
                '  <Default Extension="png" ContentType="image/png"/>',
                '  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>',
                '  <Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>',
                '</Types>',
            ]
            zf.writestr("[Content_Types].xml", "\n".join(ct_xml))

            # _rels/.rels
            root_rels = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">',
                '  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>',
                '</Relationships>',
            ]
            zf.writestr("_rels/.rels", "\n".join(root_rels))

            # word/_rels/document.xml.rels
            doc_rels = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">',
                '  <Relationship Id="rIdStyles" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>',
            ]
            for idx, _ in enumerate(figure_images, 1):
                doc_rels.append(
                    f'  <Relationship Id="rIdImg{idx}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/image{idx}.png"/>'
                )
            doc_rels.append('</Relationships>')
            zf.writestr("word/_rels/document.xml.rels", "\n".join(doc_rels))

            # Write media images
            for idx, (_, png_data, _) in enumerate(figure_images, 1):
                zf.writestr(f"word/media/image{idx}.png", png_data)

            # word/styles.xml
            styles_xml = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">',
                '  <w:docDefaults>',
                '    <w:rPrDefault><w:rPr><w:rFonts w:ascii="Liberation Sans" w:hAnsi="Liberation Sans"/><w:sz w:val="24"/></w:rPr></w:rPrDefault>',
                '  </w:docDefaults>',
                '  <w:style w:type="paragraph" w:styleId="Heading1"><w:name w:val="Heading 1"/><w:rPr><w:b/><w:sz w:val="36"/><w:color w:val="1F497D"/></w:rPr></w:style>',
                '  <w:style w:type="paragraph" w:styleId="Heading2"><w:name w:val="Heading 2"/><w:rPr><w:b/><w:sz w:val="28"/><w:color w:val="365F91"/></w:rPr></w:style>',
                '  <w:style w:type="paragraph" w:styleId="ListBullet"><w:name w:val="List Bullet"/><w:pPr><w:ind w:left="720"/></w:pPr></w:style>',
                '</w:styles>',
            ]
            zf.writestr("word/styles.xml", "\n".join(styles_xml))

            # word/document.xml body builder
            body_elems: List[str] = []

            # Project title
            doc_title = sanitize_xml(self.document.title or "GemGraph Scientific Report")
            body_elems.append(f'<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>{doc_title}</w:t></w:r></w:p>')

            # Info Sheets
            for info in info_sheets:
                body_elems.append(f'<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>Info: {sanitize_xml(info.title)}</w:t></w:r></w:p>')
                # GLP Table
                props = [(k, v) for k, v in info.constants.items() if v]
                if props:
                    body_elems.append('<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="5000" w:type="pct"/></w:tblPr>')
                    for prop_name, prop_val in props:
                        body_elems.append(
                            f'<w:tr><w:tc><w:tcPr><w:shd w:fill="F0F4F8"/></w:tcPr><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>{sanitize_xml(prop_name)}</w:t></w:r></w:p></w:tc>'
                            f'<w:tc><w:p><w:r><w:t>{sanitize_xml(prop_val)}</w:t></w:r></w:p></w:tc></w:tr>'
                        )
                    body_elems.append('</w:tbl>')

                # Experimental Notes (preserving rich text bold, italic, underline, fonts, sizes, bullets)
                notes_paras = parse_notes_to_rich_paragraphs(getattr(info, "notes_html", ""), info.notes)
                if notes_paras:
                    body_elems.append('<w:p><w:r><w:rPr><w:b/><w:i/></w:rPr><w:t>Experimental Notes &amp; Observations:</w:t></w:r></w:p>')
                    for para in notes_paras:
                        pPr_parts = []
                        if para.is_bullet:
                            pPr_parts.append('<w:pStyle w:val="ListBullet"/>')
                            pPr_parts.append(f'<w:ind w:left="{720 + para.indent * 360}"/>')
                        elif para.indent > 0:
                            pPr_parts.append(f'<w:ind w:left="{para.indent * 720}"/>')
                        pPr_str = f"<w:pPr>{''.join(pPr_parts)}</w:pPr>" if pPr_parts else ""

                        run_xmls = []
                        if para.is_bullet:
                            run_xmls.append('<w:r><w:t xml:space="preserve">• </w:t></w:r>')
                        for run in para.runs:
                            rPr_parts = []
                            if run.bold:
                                rPr_parts.append("<w:b/>")
                            if run.italic:
                                rPr_parts.append("<w:i/>")
                            if run.underline:
                                rPr_parts.append('<w:u w:val="single"/>')
                            if run.font_family:
                                rPr_parts.append(
                                    f'<w:rFonts w:ascii="{sanitize_xml(run.font_family)}" w:hAnsi="{sanitize_xml(run.font_family)}"/>'
                                )
                            if run.font_size_pt > 0:
                                rPr_parts.append(f'<w:sz w:val="{int(round(run.font_size_pt * 2))}"/>')
                            rPr_str = f"<w:rPr>{''.join(rPr_parts)}</w:rPr>" if rPr_parts else ""
                            run_xmls.append(
                                f'<w:r>{rPr_str}<w:t xml:space="preserve">{sanitize_xml(run.text)}</w:t></w:r>'
                            )
                        body_elems.append(f'<w:p>{pPr_str}{"".join(run_xmls)}</w:p>')

            # Data Tables
            for ds in data_sheets:
                body_elems.append(f'<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>Data Table: {sanitize_xml(ds.title)}</w:t></w:r></w:p>')
                df = ds.table.to_dataframe()
                body_elems.append('<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="5000" w:type="pct"/></w:tblPr>')
                # Header row
                body_elems.append('<w:tr>')
                for col in df.columns:
                    body_elems.append(f'<w:tc><w:tcPr><w:shd w:fill="E9EEF4"/></w:tcPr><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>{sanitize_xml(col)}</w:t></w:r></w:p></w:tc>')
                body_elems.append('</w:tr>')
                # Data rows (max 1000 rows to keep document performant)
                for _, row in df.head(1000).iterrows():
                    body_elems.append('<w:tr>')
                    for v in row:
                        val_str = "" if pd_isna(v) else f"{v:.6g}" if isinstance(v, (int, float, np.floating, np.integer)) else str(v)
                        body_elems.append(f'<w:tc><w:p><w:r><w:t>{sanitize_xml(val_str)}</w:t></w:r></w:p></w:tc>')
                    body_elems.append('</w:tr>')
                body_elems.append('</w:tbl>')

            # Analysis Results
            for res in result_sheets:
                body_elems.append(f'<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>Results: {sanitize_xml(res.title)} ({sanitize_xml(res.analysis_type)})</w:t></w:r></w:p>')
                for tab in res.tabs:
                    tab_name = tab.get("name", "Analysis Ledger")
                    headers = tab.get("headers", [])
                    rows = tab.get("rows", [])
                    body_elems.append(f'<w:p><w:r><w:rPr><w:b/></w:rPr><w:t>{sanitize_xml(tab_name)}</w:t></w:r></w:p>')
                    if headers:
                        body_elems.append('<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="5000" w:type="pct"/></w:tblPr>')
                        body_elems.append('<w:tr>')
                        for h in headers:
                            body_elems.append(f'<w:tc><w:tcPr><w:shd w:fill="E2EFDA"/></w:tcPr><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>{sanitize_xml(h)}</w:t></w:r></w:p></w:tc>')
                        body_elems.append('</w:tr>')
                        for r in rows:
                            body_elems.append('<w:tr>')
                            for c in r:
                                val_str = "" if c is None else str(c)
                                body_elems.append(f'<w:tc><w:p><w:r><w:t>{sanitize_xml(val_str)}</w:t></w:r></w:p></w:tc>')
                            body_elems.append('</w:tr>')
                        body_elems.append('</w:tbl>')

            # Embedded Figure Images (Graphs & Page Layouts)
            for idx, (f_title, _, is_layout) in enumerate(figure_images, 1):
                type_label = "Page Layout" if is_layout else "Graph"
                body_elems.append(f'<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>{type_label}: {sanitize_xml(f_title)}</w:t></w:r></w:p>')
                cx = 5943600 if is_layout else 5486400  # 6.5 in or 6.0 in in EMU
                cy = 4457700 if is_layout else 3657600  # 4.875 in or 4.0 in in EMU
                drawing_xml = (
                    f'<w:p><w:r><w:drawing><wp:inline distT="0" distB="0" distL="0" distR="0">'
                    f'<wp:extent cx="{cx}" cy="{cy}"/>'
                    f'<wp:docPr id="{idx}" name="Picture {idx}"/>'
                    f'<a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">'
                    f'<a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture">'
                    f'<pic:pic xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture">'
                    f'<pic:nvPicPr><pic:cNvPr id="{idx}" name="Image{idx}.png"/><pic:cNvPicPr/></pic:nvPicPr>'
                    f'<pic:blipFill><a:blip r:embed="rIdImg{idx}" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
                    f'<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr>'
                    f'</pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>'
                )
                body_elems.append(drawing_xml)
                body_elems.append(
                    f'<w:p><w:r><w:rPr><w:i/></w:rPr><w:t>Figure {idx}: {sanitize_xml(f_title)}'
                    f'{" (Layout Panel)" if is_layout else ""}</w:t></w:r></w:p>'
                )

            document_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" '
                'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
                'xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing">\n'
                '<w:body>\n' + "\n".join(body_elems) + '\n<w:sectPr/></w:body></w:document>'
            )
            zf.writestr("word/document.xml", document_xml)

        with open(file_path, "wb") as f:
            f.write(buf.getvalue())
        return file_path

    # -------------------------------------------------------------------------
    # 2. OpenDocument Text (.odt)
    # -------------------------------------------------------------------------
    def export_odt(self, file_path: str, selected_sheet_ids: Optional[List[str]] = None) -> str:
        info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets = self._get_export_items(selected_sheet_ids)

        figure_images: List[Tuple[str, bytes, bool]] = []
        target_graphs = graph_sheets if graph_sheets else (data_sheets if not layout_sheets else [])
        for g in target_graphs:
            try:
                png_bytes = render_graph_to_png_bytes(g, self.document, self.graph_canvas)
                figure_images.append((g.title, png_bytes, False))
            except Exception:
                pass

        for l in layout_sheets:
            try:
                png_bytes = render_layout_to_png_bytes(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                figure_images.append((l.title, png_bytes, True))
            except Exception:
                pass

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            # 1. mimetype (MUST be first and uncompressed)
            zf.writestr("mimetype", "application/vnd.oasis.opendocument.text", compress_type=zipfile.ZIP_STORED)

            # 2. META-INF/manifest.xml
            manifest_entries = [
                '  <manifest:file-entry manifest:full-path="/" manifest:version="1.2" manifest:media-type="application/vnd.oasis.opendocument.text"/>',
                '  <manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>',
                '  <manifest:file-entry manifest:full-path="styles.xml" manifest:media-type="text/xml"/>',
            ]
            for idx, _ in enumerate(figure_images, 1):
                manifest_entries.append(
                    f'  <manifest:file-entry manifest:full-path="Pictures/image{idx}.png" manifest:media-type="image/png"/>'
                )
            manifest_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">\n'
                + "\n".join(manifest_entries)
                + '\n</manifest:manifest>'
            )
            zf.writestr("META-INF/manifest.xml", manifest_xml)

            # Write Pictures
            for idx, (_, png_data, _) in enumerate(figure_images, 1):
                zf.writestr(f"Pictures/image{idx}.png", png_data)

            # 3. styles.xml
            styles_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<office:document-styles xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
                'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" '
                'xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0" '
                'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" office:version="1.2">\n'
                '  <office:styles>\n'
                '    <style:style style:name="Standard" style:family="paragraph"/>\n'
                '    <style:style style:name="Bold" style:family="text">\n'
                '      <style:text-properties fo:font-weight="bold"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="Italic" style:family="text">\n'
                '      <style:text-properties fo:font-style="italic"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="Underline" style:family="text">\n'
                '      <style:text-properties style:text-underline-style="solid"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="BoldItalic" style:family="text">\n'
                '      <style:text-properties fo:font-weight="bold" fo:font-style="italic"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="Serif" style:family="text">\n'
                '      <style:text-properties style:font-name="Liberation Serif" fo:font-family="Liberation Serif"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="Mono" style:family="text">\n'
                '      <style:text-properties style:font-name="Liberation Mono" fo:font-family="Liberation Mono"/>\n'
                '    </style:style>\n'
                '    <style:style style:name="Sans" style:family="text">\n'
                '      <style:text-properties style:font-name="Liberation Sans" fo:font-family="Liberation Sans"/>\n'
                '    </style:style>\n'
                '  </office:styles>\n'
                '</office:document-styles>'
            )
            zf.writestr("styles.xml", styles_xml)

            # 4. content.xml
            text_body: List[str] = []
            doc_title = sanitize_xml(self.document.title or "GemGraph Scientific Report")
            text_body.append(f'<text:h text:outline-level="1">{doc_title}</text:h>')

            for info in info_sheets:
                text_body.append(f'<text:h text:outline-level="2">Info: {sanitize_xml(info.title)}</text:h>')
                props = [(k, v) for k, v in info.constants.items() if v]
                if props:
                    text_body.append(f'<table:table table:name="Info_{sanitize_xml(info.sheet_id)}">')
                    text_body.append('<table:table-column table:number-columns-repeated="2"/>')
                    for k, v in props:
                        text_body.append(
                            f'<table:table-row>'
                            f'<table:table-cell office:value-type="string"><text:p><text:span text:style-name="Bold">{sanitize_xml(k)}</text:span></text:p></table:table-cell>'
                            f'<table:table-cell office:value-type="string"><text:p>{sanitize_xml(v)}</text:p></table:table-cell>'
                            f'</table:table-row>'
                        )
                    text_body.append('</table:table>')

                # Experimental Notes (preserving rich text)
                notes_paras = parse_notes_to_rich_paragraphs(getattr(info, "notes_html", ""), info.notes)
                if notes_paras:
                    text_body.append('<text:p><text:span text:style-name="Bold">Experimental Notes &amp; Observations:</text:span></text:p>')
                    for para in notes_paras:
                        spans = []
                        for run in para.runs:
                            st_name = ""
                            if run.bold and run.italic:
                                st_name = "BoldItalic"
                            elif run.bold:
                                st_name = "Bold"
                            elif run.italic:
                                st_name = "Italic"
                            elif run.underline:
                                st_name = "Underline"

                            f_style = ""
                            if "serif" in run.font_family.lower() and "sans" not in run.font_family.lower():
                                f_style = "Serif"
                            elif "mono" in run.font_family.lower() or "courier" in run.font_family.lower():
                                f_style = "Mono"

                            run_txt = sanitize_xml(run.text)
                            if st_name:
                                run_txt = f'<text:span text:style-name="{st_name}">{run_txt}</text:span>'
                            if f_style:
                                run_txt = f'<text:span text:style-name="{f_style}">{run_txt}</text:span>'
                            spans.append(run_txt)

                        p_content = "".join(spans)
                        if para.is_bullet:
                            text_body.append(f'<text:list><text:list-item><text:p>{p_content}</text:p></text:list-item></text:list>')
                        else:
                            text_body.append(f'<text:p>{p_content}</text:p>')

            for ds in data_sheets:
                text_body.append(f'<text:h text:outline-level="2">Data Table: {sanitize_xml(ds.title)}</text:h>')
                df = ds.table.to_dataframe()
                text_body.append(f'<table:table table:name="Data_{sanitize_xml(ds.sheet_id)}">')
                text_body.append(f'<table:table-column table:number-columns-repeated="{len(df.columns)}"/>')
                # Header row
                text_body.append('<table:table-row>')
                for col in df.columns:
                    text_body.append(f'<table:table-cell office:value-type="string"><text:p>{sanitize_xml(col)}</text:p></table:table-cell>')
                text_body.append('</table:table-row>')
                for _, row in df.head(1000).iterrows():
                    text_body.append('<table:table-row>')
                    for v in row:
                        if pd_isna(v):
                            text_body.append('<table:table-cell/>')
                        elif isinstance(v, (int, float, np.floating, np.integer)):
                            text_body.append(f'<table:table-cell office:value-type="float" office:value="{v}"><text:p>{v:.6g}</text:p></table:table-cell>')
                        else:
                            text_body.append(f'<table:table-cell office:value-type="string"><text:p>{sanitize_xml(str(v))}</text:p></table:table-cell>')
                    text_body.append('</table:table-row>')
                text_body.append('</table:table>')

            for res in result_sheets:
                text_body.append(f'<text:h text:outline-level="2">Results: {sanitize_xml(res.title)} ({sanitize_xml(res.analysis_type)})</text:h>')
                for t_idx, tab in enumerate(res.tabs):
                    t_name = tab.get("name", "Ledger")
                    headers = tab.get("headers", [])
                    rows = tab.get("rows", [])
                    text_body.append(f'<text:p><text:span text:style-name="Bold">{sanitize_xml(t_name)}</text:span></text:p>')
                    if headers:
                        text_body.append(f'<table:table table:name="Res_{sanitize_xml(res.sheet_id)}_{t_idx}">')
                        text_body.append(f'<table:table-column table:number-columns-repeated="{len(headers)}"/>')
                        text_body.append('<table:table-row>')
                        for h in headers:
                            text_body.append(f'<table:table-cell office:value-type="string"><text:p>{sanitize_xml(h)}</text:p></table:table-cell>')
                        text_body.append('</table:table-row>')
                        for r in rows:
                            text_body.append('<table:table-row>')
                            for c in r:
                                text_body.append(f'<table:table-cell office:value-type="string"><text:p>{sanitize_xml("" if c is None else str(c))}</text:p></table:table-cell>')
                            text_body.append('</table:table-row>')
                        text_body.append('</table:table>')

            for idx, (f_title, _, is_layout) in enumerate(figure_images, 1):
                type_label = "Page Layout" if is_layout else "Graph"
                text_body.append(f'<text:h text:outline-level="2">{type_label}: {sanitize_xml(f_title)}</text:h>')
                w_cm = "16cm" if is_layout else "15cm"
                h_cm = "12cm" if is_layout else "10cm"
                text_body.append(
                    f'<text:p><draw:frame draw:name="Figure_{idx}" text:anchor-type="paragraph" svg:width="{w_cm}" svg:height="{h_cm}">'
                    f'<draw:image xlink:href="Pictures/image{idx}.png" xlink:type="simple" xlink:show="embed" xlink:actuate="onLoad"/>'
                    f'</draw:frame></text:p>'
                )
                text_body.append(
                    f'<text:p><text:span text:style-name="Italic">Figure {idx}: {sanitize_xml(f_title)}'
                    f'{" (Layout Panel)" if is_layout else ""}</text:span></text:p>'
                )

            content_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
                'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" '
                'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" '
                'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
                'xmlns:draw="urn:oasis:names:tc:opendocument:xmlns:drawing:1.0" '
                'xmlns:xlink="http://www.w3.org/1999/xlink" '
                'xmlns:svg="urn:oasis:names:tc:opendocument:xmlns:svg-compatible:1.0" office:version="1.2">\n'
                '  <office:body>\n'
                '    <office:text>\n' + "\n".join(text_body) + '\n    </office:text>\n'
                '  </office:body>\n'
                '</office:document-content>'
            )
            zf.writestr("content.xml", content_xml)

        with open(file_path, "wb") as f:
            f.write(buf.getvalue())
        return file_path

    # -------------------------------------------------------------------------
    # 3. Excel Workbook (.xlsx)
    # -------------------------------------------------------------------------
    def export_xlsx(self, file_path: str, selected_sheet_ids: Optional[List[str]] = None) -> str:
        info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets = self._get_export_items(selected_sheet_ids)

        worksheets: List[Tuple[str, List[List[Any]]]] = []

        # Info sheet tab
        if info_sheets:
            info_rows: List[List[Any]] = [["Category", "Property", "Value"]]
            for info in info_sheets:
                info_rows.append([f"Sheet: {info.title}", "", ""])
                for k, v in info.constants.items():
                    if v:
                        info_rows.append(["GLP Specification", k, v])
                if info.notes:
                    info_rows.append(["Experimental Notes", "Protocol Notes", info.notes])
            worksheets.append(("Info Sheets", info_rows))

        # Data tables
        for ds in data_sheets:
            df = ds.table.to_dataframe()
            tab_rows: List[List[Any]] = [list(df.columns)]
            for _, r in df.head(5000).iterrows():
                tab_rows.append(list(r))
            worksheets.append((sanitize_sheet_name(ds.title), tab_rows))

        # Results
        for res in result_sheets:
            for t_idx, tab in enumerate(res.tabs):
                name = sanitize_sheet_name(f"{res.title}_{tab.get('name', 'Tab')}")
                tab_rows = []
                headers = tab.get("headers", [])
                if headers:
                    tab_rows.append(headers)
                for row_data in tab.get("rows", []):
                    tab_rows.append(row_data)
                worksheets.append((name, tab_rows))

        # Graph sheets: render PNG bytes and create dedicated worksheets with drawing
        graph_images: List[Tuple[str, bytes]] = []
        graph_sheet_indices: List[Tuple[int, int]] = []  # (worksheet_idx_1based, image_idx_1based)

        target_graphs = graph_sheets if graph_sheets else (data_sheets if not layout_sheets else [])
        for g in target_graphs:
            try:
                png_bytes = render_graph_to_png_bytes(g, self.document, self.graph_canvas)
                graph_images.append((g.title, png_bytes))
                g_tab_name = sanitize_sheet_name(f"Graph_{g.title}")
                worksheets.append((g_tab_name, [[f"Graph: {g.title}"]]))
                img_idx = len(graph_images)
                ws_idx = len(worksheets)
                graph_sheet_indices.append((ws_idx, img_idx))
            except Exception:
                pass

        for l in layout_sheets:
            try:
                png_bytes = render_layout_to_png_bytes(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                graph_images.append((f"Layout_{l.title}", png_bytes))
                l_tab_name = sanitize_sheet_name(f"Layout_{l.title}")
                worksheets.append((l_tab_name, [[f"Layout: {l.title}"]]))
                img_idx = len(graph_images)
                ws_idx = len(worksheets)
                graph_sheet_indices.append((ws_idx, img_idx))
            except Exception:
                pass

        if not worksheets:
            worksheets.append(("GemGraph Data", [["Empty Project"]]))

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            # [Content_Types].xml
            ct_lines = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">',
                '  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
                '  <Default Extension="xml" ContentType="application/xml"/>',
                '  <Default Extension="png" ContentType="image/png"/>',
                '  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>',
                '  <Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>',
            ]
            for idx in range(1, len(worksheets) + 1):
                ct_lines.append(
                    f'  <Override PartName="/xl/worksheets/sheet{idx}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
                )
            for ws_idx, img_idx in graph_sheet_indices:
                ct_lines.append(
                    f'  <Override PartName="/xl/drawings/drawing{img_idx}.xml" ContentType="application/vnd.openxmlformats-officedocument.drawing+xml"/>'
                )
            ct_lines.append('</Types>')
            zf.writestr("[Content_Types].xml", "\n".join(ct_lines))

            # _rels/.rels
            root_rels = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">',
                '  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>',
                '</Relationships>',
            ]
            zf.writestr("_rels/.rels", "\n".join(root_rels))

            # xl/_rels/workbook.xml.rels
            wb_rels = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">',
                '  <Relationship Id="rIdStyles" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>',
            ]
            for idx in range(1, len(worksheets) + 1):
                wb_rels.append(
                    f'  <Relationship Id="rId{idx}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet{idx}.xml"/>'
                )
            wb_rels.append('</Relationships>')
            zf.writestr("xl/_rels/workbook.xml.rels", "\n".join(wb_rels))

            # xl/styles.xml
            styles_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">\n'
                '  <fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts>\n'
                '  <fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills>\n'
                '  <borders count="1"><border><left/><right/><top/><bottom/></border></borders>\n'
                '  <cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>\n'
                '  <cellXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/></cellXfs>\n'
                '</styleSheet>'
            )
            zf.writestr("xl/styles.xml", styles_xml)

            # xl/workbook.xml
            wb_sheets = []
            used_names = set()
            for idx, (sheet_title, _) in enumerate(worksheets, 1):
                safe_name = sheet_title
                suffix = 1
                while safe_name in used_names:
                    safe_name = f"{sheet_title[:28]}_{suffix}"
                    suffix += 1
                used_names.add(safe_name)
                wb_sheets.append(f'    <sheet name="{sanitize_xml(safe_name)}" sheetId="{idx}" r:id="rId{idx}"/>')

            wb_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
                'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">\n'
                '  <sheets>\n' + "\n".join(wb_sheets) + '\n  </sheets>\n</workbook>'
            )
            zf.writestr("xl/workbook.xml", wb_xml)

            # Write media images
            for img_idx, (_, png_data) in enumerate(graph_images, 1):
                zf.writestr(f"xl/media/image{img_idx}.png", png_data)

            # Map from worksheet index to (drawing_idx, img_idx)
            ws_to_drawing = {ws_i: img_i for ws_i, img_i in graph_sheet_indices}

            # Write drawings and their rels
            for ws_i, img_i in graph_sheet_indices:
                # xl/worksheets/_rels/sheetN.xml.rels
                sheet_rel = (
                    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                    '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
                    f'  <Relationship Id="rIdDraw1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/drawing" Target="../drawings/drawing{img_i}.xml"/>\n'
                    '</Relationships>'
                )
                zf.writestr(f"xl/worksheets/_rels/sheet{ws_i}.xml.rels", sheet_rel)

                # xl/drawings/drawingN.xml
                drawing_xml = (
                    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                    '<xdr:wsDr xmlns:xdr="http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing" '
                    'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">\n'
                    '  <xdr:oneCellAnchor>\n'
                    '    <xdr:from><xdr:col>0</xdr:col><xdr:colOff>0</xdr:colOff><xdr:row>2</xdr:row><xdr:rowOff>0</xdr:rowOff></xdr:from>\n'
                    '    <xdr:ext cx="5486400" cy="3657600"/>\n'
                    '    <xdr:pic>\n'
                    f'      <xdr:nvPicPr><xdr:cNvPr id="{img_i}" name="Graph {img_i}"/><xdr:cNvPicPr><a:picLocks noChangeAspect="1"/></xdr:cNvPicPr></xdr:nvPicPr>\n'
                    '      <xdr:blipFill>\n'
                    f'        <a:blip xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" r:embed="rIdImg1"/>\n'
                    '        <a:stretch><a:fillRect/></a:stretch>\n'
                    '      </xdr:blipFill>\n'
                    '      <xdr:spPr>\n'
                    '        <a:xfrm><a:off x="0" y="0"/><a:ext cx="5486400" cy="3657600"/></a:xfrm>\n'
                    '        <a:prstGeom prst="rect"><a:avLst/></a:prstGeom>\n'
                    '      </xdr:spPr>\n'
                    '    </xdr:pic>\n'
                    '    <xdr:clientData/>\n'
                    '  </xdr:oneCellAnchor>\n'
                    '</xdr:wsDr>'
                )
                zf.writestr(f"xl/drawings/drawing{img_i}.xml", drawing_xml)

                # xl/drawings/_rels/drawingN.xml.rels
                draw_rel = (
                    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                    '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
                    f'  <Relationship Id="rIdImg1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="../media/image{img_i}.png"/>\n'
                    '</Relationships>'
                )
                zf.writestr(f"xl/drawings/_rels/drawing{img_i}.xml.rels", draw_rel)

            # xl/worksheets/sheetN.xml
            for idx, (_, rows) in enumerate(worksheets, 1):
                has_drawing = idx in ws_to_drawing
                drawing_decl = ' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"' if has_drawing else ''
                sheet_lines = [
                    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                    f'<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"{drawing_decl}>',
                    '  <sheetData>',
                ]
                for r_idx, row_vals in enumerate(rows, 1):
                    sheet_lines.append(f'    <row r="{r_idx}">')
                    for c_idx, val in enumerate(row_vals):
                        cref = f"{col_letter(c_idx)}{r_idx}"
                        if pd_isna(val):
                            continue
                        elif isinstance(val, (int, float, np.floating, np.integer)):
                            if math.isinf(val) or math.isnan(val):
                                sheet_lines.append(f'      <c r="{cref}" t="inlineStr"><is><t>{val}</t></is></c>')
                            else:
                                sheet_lines.append(f'      <c r="{cref}"><v>{val}</v></c>')
                        else:
                            sheet_lines.append(f'      <c r="{cref}" t="inlineStr"><is><t>{sanitize_xml(str(val))}</t></is></c>')
                    sheet_lines.append('    </row>')
                sheet_lines.append('  </sheetData>')
                if has_drawing:
                    sheet_lines.append('  <drawing r:id="rIdDraw1"/>')
                sheet_lines.append('</worksheet>')
                zf.writestr(f"xl/worksheets/sheet{idx}.xml", "\n".join(sheet_lines))

        with open(file_path, "wb") as f:
            f.write(buf.getvalue())
        return file_path

    # -------------------------------------------------------------------------
    # 4. OpenDocument Spreadsheet (.ods)
    # -------------------------------------------------------------------------
    def export_ods(self, file_path: str, selected_sheet_ids: Optional[List[str]] = None) -> str:
        info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets = self._get_export_items(selected_sheet_ids)

        tables: List[Tuple[str, List[List[Any]]]] = []

        if info_sheets:
            info_rows: List[List[Any]] = [["Category", "Property", "Value"]]
            for info in info_sheets:
                info_rows.append([f"Sheet: {info.title}", "", ""])
                for k, v in info.constants.items():
                    if v:
                        info_rows.append(["GLP Specification", k, v])
                if info.notes:
                    info_rows.append(["Experimental Notes", "Protocol Notes", info.notes])
            tables.append(("Info Sheets", info_rows))

        for ds in data_sheets:
            df = ds.table.to_dataframe()
            t_rows = [list(df.columns)]
            for _, r in df.head(5000).iterrows():
                t_rows.append(list(r))
            tables.append((sanitize_sheet_name(ds.title), t_rows))

        for res in result_sheets:
            for tab in res.tabs:
                name = sanitize_sheet_name(f"{res.title}_{tab.get('name', 'Tab')}")
                t_rows = []
                headers = tab.get("headers", [])
                if headers:
                    t_rows.append(headers)
                for row_data in tab.get("rows", []):
                    t_rows.append(row_data)
                tables.append((name, t_rows))

        # Render graph and layout sheets to PNG bytes
        graph_images: List[Tuple[str, bytes]] = []
        target_graphs = graph_sheets if graph_sheets else (data_sheets if not layout_sheets else [])
        for g in target_graphs:
            try:
                png_bytes = render_graph_to_png_bytes(g, self.document, self.graph_canvas)
                graph_images.append((g.title, png_bytes))
            except Exception:
                pass

        for l in layout_sheets:
            try:
                png_bytes = render_layout_to_png_bytes(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                graph_images.append((f"Layout_{l.title}", png_bytes))
            except Exception:
                pass

        if not tables and not graph_images:
            tables.append(("GemGraph Data", [["Empty Project"]]))

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            # 1. mimetype (first, stored uncompressed)
            zf.writestr("mimetype", "application/vnd.oasis.opendocument.spreadsheet", compress_type=zipfile.ZIP_STORED)

            # 2. META-INF/manifest.xml
            manifest_entries = [
                '  <manifest:file-entry manifest:full-path="/" manifest:version="1.2" manifest:media-type="application/vnd.oasis.opendocument.spreadsheet"/>',
                '  <manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>',
                '  <manifest:file-entry manifest:full-path="styles.xml" manifest:media-type="text/xml"/>',
            ]
            for idx, _ in enumerate(graph_images, 1):
                manifest_entries.append(
                    f'  <manifest:file-entry manifest:full-path="Pictures/image{idx}.png" manifest:media-type="image/png"/>'
                )
            manifest_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">\n'
                + "\n".join(manifest_entries)
                + '\n</manifest:manifest>'
            )
            zf.writestr("META-INF/manifest.xml", manifest_xml)

            # Write Pictures
            for idx, (_, png_data) in enumerate(graph_images, 1):
                zf.writestr(f"Pictures/image{idx}.png", png_data)

            # 3. styles.xml
            styles_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<office:document-styles xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
                'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" office:version="1.2">\n'
                '  <office:styles>\n'
                '    <style:style style:name="Default" style:family="table-cell"/>\n'
                '  </office:styles>\n'
                '</office:document-styles>'
            )
            zf.writestr("styles.xml", styles_xml)

            # 4. content.xml
            content_tables: List[str] = []
            used_names = set()
            for t_title, rows in tables:
                safe_name = t_title
                suffix = 1
                while safe_name in used_names:
                    safe_name = f"{t_title[:28]}_{suffix}"
                    suffix += 1
                used_names.add(safe_name)

                content_tables.append(f'      <table:table table:name="{sanitize_xml(safe_name)}">')
                for row_data in rows:
                    content_tables.append('        <table:table-row>')
                    for val in row_data:
                        if pd_isna(val):
                            content_tables.append('          <table:table-cell/>')
                        elif isinstance(val, (int, float, np.floating, np.integer)):
                            if math.isinf(val) or math.isnan(val):
                                content_tables.append(f'          <table:table-cell office:value-type="string"><text:p>{val}</text:p></table:table-cell>')
                            else:
                                content_tables.append(f'          <table:table-cell office:value-type="float" office:value="{val}"><text:p>{val}</text:p></table:table-cell>')
                        else:
                            content_tables.append(f'          <table:table-cell office:value-type="string"><text:p>{sanitize_xml(str(val))}</text:p></table:table-cell>')
                    content_tables.append('        </table:table-row>')
                content_tables.append('      </table:table>')

            # Add graph sheets as table tabs with embedded images
            for idx, (g_title, _) in enumerate(graph_images, 1):
                safe_g_name = sanitize_sheet_name(f"Graph_{g_title}")
                suffix = 1
                while safe_g_name in used_names:
                    safe_g_name = f"Graph_{g_title[:22]}_{suffix}"
                    suffix += 1
                used_names.add(safe_g_name)

                content_tables.append(
                    f'      <table:table table:name="{sanitize_xml(safe_g_name)}">\n'
                    '        <table:table-row>\n'
                    '          <table:table-cell office:value-type="string">\n'
                    f'            <text:p>Graph: {sanitize_xml(g_title)}</text:p>\n'
                    f'            <draw:frame draw:name="Graph_{idx}" text:anchor-type="paragraph" svg:width="15cm" svg:height="10cm">\n'
                    f'              <draw:image xlink:href="Pictures/image{idx}.png" xlink:type="simple" xlink:show="embed" xlink:actuate="onLoad"/>\n'
                    '            </draw:frame>\n'
                    '          </table:table-cell>\n'
                    '        </table:table-row>\n'
                    '      </table:table>'
                )

            content_xml = (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
                'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
                'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" '
                'xmlns:draw="urn:oasis:names:tc:opendocument:xmlns:drawing:1.0" '
                'xmlns:xlink="http://www.w3.org/1999/xlink" '
                'xmlns:svg="urn:oasis:names:tc:opendocument:xmlns:svg-compatible:1.0" office:version="1.2">\n'
                '  <office:body>\n'
                '    <office:spreadsheet>\n' + "\n".join(content_tables) + '\n    </office:spreadsheet>\n'
                '  </office:body>\n'
                '</office:document-content>'
            )
            zf.writestr("content.xml", content_xml)

        with open(file_path, "wb") as f:
            f.write(buf.getvalue())
        return file_path

    # -------------------------------------------------------------------------
    # 5. Portable Document Format (.pdf)
    # -------------------------------------------------------------------------
    def export_pdf(self, file_path: str, selected_sheet_ids: Optional[List[str]] = None) -> str:
        info_sheets, data_sheets, result_sheets, graph_sheets, layout_sheets = self._get_export_items(selected_sheet_ids)

        # If ONLY layout sheets are requested for PDF export, render each layout at 300 DPI on its own page
        # using QPdfWriter and QPainter directly to preserve exact physical page dimensions and aspect ratios.
        if layout_sheets and not (info_sheets or data_sheets or result_sheets or graph_sheets):
            writer = QPdfWriter(file_path)
            writer.setResolution(300)
            painter = QPainter(writer)
            try:
                for idx, l in enumerate(layout_sheets):
                    if idx > 0:
                        writer.newPage()
                    pt_w, pt_h = l.get_dimensions_pt()
                    writer.setPageSize(QPageSize(QSizeF(pt_w, pt_h), QPageSize.Unit.Point))

                    if l.orientation.lower() == "landscape":
                        writer.setPageOrientation(QPageLayout.Orientation.Landscape)
                    else:
                        writer.setPageOrientation(QPageLayout.Orientation.Portrait)

                    img = render_layout_to_image(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                    page_rect = QRectF(0, 0, writer.width(), writer.height())
                    painter.drawImage(page_rect, img)
            finally:
                painter.end()
            return file_path

        html_parts: List[str] = [
            """<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  body { font-family: "Liberation Sans", "DejaVu Sans", sans-serif; font-size: 10pt; color: #1a1a1a; margin: 15px; }
  h1 { font-size: 18pt; color: #1f4e79; border-bottom: 2px solid #1f4e79; padding-bottom: 4px; margin-bottom: 12px; }
  h2 { font-size: 13pt; color: #2f5597; margin-top: 16px; margin-bottom: 8px; }
  h3 { font-size: 11pt; color: #333333; margin-top: 10px; margin-bottom: 4px; }
  table { border-collapse: collapse; width: 100%; margin-bottom: 14px; font-size: 9pt; }
  th { background-color: #f2f4f7; color: #111; font-weight: bold; border: 1px solid #d0d7de; padding: 4px 8px; text-align: left; }
  td { border: 1px solid #d0d7de; padding: 4px 8px; vertical-align: top; }
  tr:nth-child(even) td { background-color: #fafbfc; }
  .notes-box { background-color: #fdfdfd; border: 1px solid #e1e4e8; border-left: 4px solid #2f5597; padding: 8px; margin: 8px 0; }
  .graph-container { text-align: center; margin: 16px 0; }
  .graph-container img { max-width: 100%; height: auto; border: 1px solid #e1e4e8; }
</style>
</head>
<body>
"""
        ]

        doc_title = sanitize_xml(self.document.title or "GemGraph Scientific Report")
        html_parts.append(f"<h1>{doc_title}</h1>")

        # Info Sheets
        for info in info_sheets:
            html_parts.append(f"<h2>Info Sheet: {sanitize_xml(info.title)}</h2>")
            props = [(k, v) for k, v in info.constants.items() if v]
            if props:
                html_parts.append("<table><tr><th style='width: 35%;'>GLP Property</th><th>Specification / Value</th></tr>")
                for k, v in props:
                    html_parts.append(f"<tr><td><b>{sanitize_xml(k)}</b></td><td>{sanitize_xml(v)}</td></tr>")
                html_parts.append("</table>")

            if getattr(info, "notes_html", ""):
                html_parts.append(f"<div class='notes-box'><b>Experimental Notes:</b><br>{info.notes_html}</div>")
            elif info.notes:
                notes_escaped = "<br>".join(sanitize_xml(l) for l in info.notes.splitlines())
                html_parts.append(f"<div class='notes-box'><b>Experimental Notes:</b><br>{notes_escaped}</div>")

        # Data Tables
        for ds in data_sheets:
            html_parts.append(f"<h2>Data Table: {sanitize_xml(ds.title)}</h2>")
            df = ds.table.to_dataframe()
            html_parts.append("<table><tr>")
            for col in df.columns:
                html_parts.append(f"<th>{sanitize_xml(col)}</th>")
            html_parts.append("</tr>")
            for _, r in df.head(100).iterrows():
                html_parts.append("<tr>")
                for v in r:
                    val_str = "" if pd_isna(v) else f"{v:.6g}" if isinstance(v, (int, float, np.floating, np.integer)) else str(v)
                    html_parts.append(f"<td>{sanitize_xml(val_str)}</td>")
                html_parts.append("</tr>")
            html_parts.append("</table>")

        # Result Sheets
        for res in result_sheets:
            html_parts.append(f"<h2>Analysis Results: {sanitize_xml(res.title)} ({sanitize_xml(res.analysis_type)})</h2>")
            for tab in res.tabs:
                t_name = tab.get("name", "Ledger")
                headers = tab.get("headers", [])
                rows = tab.get("rows", [])
                html_parts.append(f"<h3>{sanitize_xml(t_name)}</h3>")
                if headers:
                    html_parts.append("<table><tr>")
                    for h in headers:
                        html_parts.append(f"<th>{sanitize_xml(h)}</th>")
                    html_parts.append("</tr>")
                    for r in rows:
                        html_parts.append("<tr>")
                        for c in r:
                            val_str = "" if c is None else str(c)
                            html_parts.append(f"<td>{sanitize_xml(val_str)}</td>")
                        html_parts.append("</tr>")
                    html_parts.append("</table>")

        # Graphs
        target_graphs = graph_sheets if graph_sheets else (data_sheets if not layout_sheets else [])
        for g in target_graphs:
            html_parts.append(f"<h2>Graph: {sanitize_xml(g.title)}</h2>")
            try:
                png_bytes = render_graph_to_png_bytes(g, self.document, self.graph_canvas)
                b64_str = base64.b64encode(png_bytes).decode("ascii")
                html_parts.append(f"<div class='graph-container'><img src='data:image/png;base64,{b64_str}' /></div>")
            except Exception as e:
                html_parts.append(f"<p><i>(Graph render unavailable: {sanitize_xml(str(e))})</i></p>")

        # Page Layouts
        for idx, l in enumerate(layout_sheets, 1):
            html_parts.append(f"<h2>Page Layout: {sanitize_xml(l.title)}</h2>")
            try:
                png_bytes = render_layout_to_png_bytes(l, document=self.document, dpi=300, graph_canvas=self.graph_canvas)
                b64_str = base64.b64encode(png_bytes).decode("ascii")
                html_parts.append(
                    f"<div class='graph-container'><img src='data:image/png;base64,{b64_str}' />"
                    f"<p><i>Figure {len(target_graphs) + idx}: {sanitize_xml(l.title)} (Layout Panel)</i></p></div>"
                )
            except Exception as e:
                html_parts.append(f"<p><i>(Layout render unavailable: {sanitize_xml(str(e))})</i></p>")

        html_parts.append("</body></html>")
        full_html = "\n".join(html_parts)

        # Print via QTextDocument + QPdfWriter
        doc = QTextDocument()
        doc.setHtml(full_html)

        writer = QPdfWriter(file_path)
        writer.setPageSize(QPageSize(QPageSize.PageSizeId.A4))
        writer.setResolution(300)
        doc.setPageSize(QSizeF(writer.width(), writer.height()))
        doc.print(writer)

        return file_path
